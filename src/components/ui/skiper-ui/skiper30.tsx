"use client";

import { motion, MotionValue, useScroll, useTransform } from "framer-motion";
import Lenis from "lenis";
import { useEffect, useRef, useState, useMemo } from "react";
import { useGetMenuItemsQuery } from "@/app/store/menuApi";
import { toFrontendApiAssetUrl, DEFAULT_FOOD_IMAGE } from "@/lib/catalog-media";

const Skiper30 = () => {
  const gallery = useRef<HTMLDivElement>(null);
  const [dimension, setDimension] = useState({ width: 0, height: 0 });

  const { data: menuItems = [] } = useGetMenuItemsQuery();
  
  // Get unique images from menu items
  const dynamicImages = useMemo(() => {
    if (!menuItems || menuItems.length === 0) return [];
    
    // Extract thumbnails from all items
    const allImages = menuItems
      .filter((item) => Boolean(item.thumbnail))
      .map((item) => toFrontendApiAssetUrl(item.thumbnail as string));
      
    // Return unique images or fallback if empty
    return Array.from(new Set(allImages)).slice(0, 12);
  }, [menuItems]);
  
  // Ensure we have 12 images by repeating if necessary
  const displayImages = useMemo(() => {
    if (dynamicImages.length === 0) {
      return Array(12).fill(DEFAULT_FOOD_IMAGE);
    }
    
    const result = [...dynamicImages];
    while (result.length < 12) {
      result.push(dynamicImages[result.length % dynamicImages.length]);
    }
    return result;
  }, [dynamicImages]);

  const { scrollYProgress } = useScroll({
    target: gallery,
    offset: ["start end", "end start"],
  });

  const { height } = dimension;
  const y = useTransform(scrollYProgress, [0, 1], [0, height * 2]);
  const y2 = useTransform(scrollYProgress, [0, 1], [0, height * 3.3]);
  const y3 = useTransform(scrollYProgress, [0, 1], [0, height * 1.25]);
  const y4 = useTransform(scrollYProgress, [0, 1], [0, height * 3]);

  useEffect(() => {
    const lenis = new Lenis();

    const raf = (time: number) => {
      lenis.raf(time);
      requestAnimationFrame(raf);
    };

    const resize = () => {
      setDimension({ width: window.innerWidth, height: window.innerHeight });
    };

    window.addEventListener("resize", resize);
    requestAnimationFrame(raf);
    resize();

    return () => {
      window.removeEventListener("resize", resize);
    };
  }, []);

  return (
    <main className="w-full bg-[#eee] text-black">
      {/* <div className="font-geist flex h-screen items-center justify-center gap-2">
        <div className="absolute left-1/2 top-[10%] grid -translate-x-1/2 content-start justify-items-center gap-6 text-center text-black">
          <span className="relative max-w-[12ch] text-xs uppercase leading-tight opacity-40 after:absolute after:left-1/2 after:top-full after:h-16 after:w-px after:bg-gradient-to-b after:from-white after:to-black after:content-['']">
            scroll down to see
          </span>
        </div>
      </div> */}

      <div
        ref={gallery}
        className="relative box-border flex h-[175vh] gap-[2vw] overflow-hidden bg-white p-[2vw]"
      >
        <Column images={[displayImages[0], displayImages[1], displayImages[2]]} y={y} />
        <Column images={[displayImages[3], displayImages[4], displayImages[5]]} y={y2} />
        <Column images={[displayImages[6], displayImages[7], displayImages[8]]} y={y3} />
        <Column images={[displayImages[9], displayImages[10], displayImages[11]]} y={y4} />
      </div>
      {/* <div className="font-geist relative flex h-screen items-center justify-center gap-2">
        <div className="absolute left-1/2 top-[10%] grid -translate-x-1/2 content-start justify-items-center gap-6 text-center text-black">
          <span className="relative max-w-[12ch] text-xs uppercase leading-tight opacity-40 after:absolute after:left-1/2 after:top-full after:h-16 after:w-px after:bg-gradient-to-b after:from-white after:to-black after:content-['']">
            scroll Up to see
          </span>
        </div>
      </div> */}
    </main>
  );
};

type ColumnProps = {
  images: string[];
  y: MotionValue<number>;
};

const Column = ({ images, y }: ColumnProps) => {
  return (
    <motion.div
      className="relative border -top-[45%] flex h-full w-1/4 min-w-[250px] flex-col gap-[2vw] first:top-[-45%] [&:nth-child(2)]:top-[-95%] [&:nth-child(3)]:top-[-45%] [&:nth-child(4)]:top-[-75%]"
      style={{ y }}
    >
      {images.map((src, i) => (
        <div key={i} className="relative h-full w-full overflow-hidden">
          <img
            src={`${src}`}
            alt="image"
            className="pointer-events-none object-cover"
          />
        </div>
      ))}
    </motion.div>
  );
};

export { Skiper30 };

